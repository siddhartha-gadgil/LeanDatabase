#!/usr/bin/env python3
"""Overnight runner: run `sql_equiv_llm` over all Literature + Calcite Problems, resolve each to a
concrete artifact (Proven/ with the real proof, or CounterExample/ with a `plausible_sql` witness),
verify the artifact compiles WITHOUT the LLM, and write a report. Parallelised.

Outputs: Bench/<ds>/Proven/<n>.lean, Bench/<ds>/CounterExample/<n>.lean, and scripts/overnight_report.md
plus overnight_results.csv.
"""
import csv, json, os, re, subprocess, sys, time
from concurrent.futures import ThreadPoolExecutor, as_completed
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
try:
    from validate_disproofs import is_real_disproof   # sqlglot bag-semantics disproof gate
except Exception:
    is_real_disproof = None

ROOT = "/home/anirudhgupta/LeanDatabase"
# pairs.json (raw SQL + schemas) per dataset, for the real-SQL disproof gate. Loaded lazily.
_PAIRS = {}
def pair_for(ds, n):
    if ds not in _PAIRS:
        try:
            _PAIRS[ds] = {x['id'].split(':')[0]: x
                          for x in json.load(open(os.path.join(ROOT, "Bench", ds, "pairs.json")))}
        except Exception:
            _PAIRS[ds] = {}
    return _PAIRS[ds].get(n)
DATASETS = ["Literature", "Calcite"]
WORKERS = int(os.environ.get("WORKERS", "8"))
PER_FILE_TIMEOUT = 700
COMMENT = "-- generated by `sql_equiv_llm`"

def wire(src):
    s = re.sub(r':= by\s+first \| sql_equiv \| sorry', ':= by first | sql_equiv_llm | sorry', src)
    s = re.sub(r':= by\s+sql_equiv\b(?!_)', ':= by first | sql_equiv_llm | sorry', s)
    return s

def lean(path):
    t0 = time.time()
    try:
        r = subprocess.run(["lake", "env", "lean", path], cwd=ROOT, capture_output=True,
                           text=True, timeout=PER_FILE_TIMEOUT)
        out = r.stdout + r.stderr
    except subprocess.TimeoutExpired:
        out = "<<<TIMEOUT>>>"
    return out, time.time() - t0

def parse(out):
    m = re.search(r'<<<SQLLLM>>>OUTCOME=(\w+);METHOD=([\w+.-]+)', out)
    if m:
        outcome, method = m.group(1), m.group(2)
    elif "<<<TIMEOUT>>>" in out:
        outcome, method = "TIMEOUT", ""
    elif re.search(r'error:', out):
        outcome, method = "ELAB_ERROR", ""
    else:
        outcome, method = "INCONCLUSIVE", ""
    pm = re.search(r'<<<SQLLLM_PROOF_BEGIN>>>\n(.*?)\n<<<SQLLLM_PROOF_END>>>', out, re.DOTALL)
    cm = re.search(r'<<<SQLLLM_CX_BEGIN>>>\n(.*?)\n<<<SQLLLM_CX_END>>>', out, re.DOTALL)
    cost = re.search(r'cost: ([\d.]+)¢', out)
    return outcome, method, (pm.group(1).strip() if pm else None), \
        (cm.group(1).strip() if cm else None), (float(cost.group(1)) if cost else 0.0)

def split_theorem(src):
    """Return (prefix_upto_theorem, binders, body, ns) or None."""
    key = "theorem eq"
    i = src.find(key)
    if i < 0: return None
    j = i + len(key); depth = 0
    while j < len(src):
        c = src[j]
        if c == '(': depth += 1
        elif c == ')': depth -= 1
        elif c == ':' and depth == 0: break
        j += 1
    binders = src[i + len(key):j].strip()
    k = src.find(":= by", j)
    if k < 0: return None
    body = src[j + 1:k].strip()
    nsm = re.search(r'namespace\s+(\S+)', src)
    ns = nsm.group(1) if nsm else "N"
    return src[:i], binders, body, ns

def gen_proven(src, proof):
    k = src.find(":= by")
    ns = (re.search(r'namespace\s+(\S+)', src) or [None, "N"])[1] if isinstance(re.search(r'namespace\s+(\S+)', src), re.Match) else "N"
    nsm = re.search(r'namespace\s+(\S+)', src); ns = nsm.group(1) if nsm else "N"
    proof_indented = "\n  ".join(proof.splitlines())
    return src[:k] + f":= by\n  {proof_indented}\n  {COMMENT}\n\nend {ns}\n"

def gen_counterexample(src, cx_json):
    parts = split_theorem(src)
    if not parts: return None
    prefix, binders, body, ns = parts
    # ensure the Counterex module is imported
    if "SQLEquivCounterex" not in prefix:
        prefix = prefix.replace("import LeanDatabase.SQLSyntax",
                                "import LeanDatabase.SQLSyntax\nimport LeanDatabase.LlmTactic.SQLEquivCounterex\nopen LeanDatabase.SQLEquivLLM", 1)
    lit = '"' + cx_json.replace('\\', '\\\\').replace('"', '\\"') + '"'
    return (prefix + "theorem not_equivalent :\n"
            f"    ¬ (∀ {binders},\n{body}) := by\n  plausible_sql {lit}\n  {COMMENT}\n\nend {ns}\n")

def verify(path):
    out, _ = lean(path)
    bad = re.search(r'error:', out) or "declaration uses 'sorry'" in out or "<<<TIMEOUT>>>" in out
    return not bad

def process(ds, path):
    n = os.path.basename(path)[:-5]
    src = open(path).read()
    tmp = os.path.join(ROOT, "Bench", ds, "Problems", f".{n}.wired.lean")
    open(tmp, "w").write(wire(src))
    out, dt = lean(tmp)
    try: os.remove(tmp)
    except OSError: pass
    outcome, method, proof, cx, cost = parse(out)
    verified = ""
    dest = ""
    if outcome == "PROVED" and proof:
        d = os.path.join(ROOT, "Bench", ds, "Proven"); os.makedirs(d, exist_ok=True)
        dest = os.path.join(d, f"{n}.lean")
        open(dest, "w").write(gen_proven(src, proof))
        if verify(dest):
            verified = "yes"
        else:
            # fall back to sql_equiv_safe for step-0 proofs
            open(dest, "w").write(gen_proven(src, "sql_equiv_safe"))
            verified = "yes(safe)" if verify(dest) else "NO"
            if verified == "NO": os.remove(dest); dest = ""; outcome = "INCONCLUSIVE"
    elif outcome == "DISPROVED" and cx:
        # GATE: our Lean disproof is set-semantics; a counterexample that differs only as a SET but is
        # equal as a BAG is spurious (our model bug), not a real disproof. Certify against a real SQL
        # engine (bag semantics) via sqlglot and REJECT spurious ones so they are never written.
        p = pair_for(ds, n)
        real = is_real_disproof(p['schemas'], p['first'], p['second'], cx) \
               if (is_real_disproof and p) else None
        if real is False:
            outcome = "SPURIOUS(set-only; real SQL bag-equal → model bug)"
        else:
            d = os.path.join(ROOT, "Bench", ds, "CounterExample"); os.makedirs(d, exist_ok=True)
            dest = os.path.join(d, f"{n}.lean")
            art = gen_counterexample(src, cx)
            if art:
                open(dest, "w").write(art)
                verified = ("yes" if real else "yes(sqlglot-inconclusive)") if verify(dest) else "NO"
                if verified == "NO": os.remove(dest); dest = ""; outcome = "DISPROVED(unverified-artifact)"
    return {"dataset": ds, "file": n, "outcome": outcome, "method": method,
            "cost_cents": round(cost, 4), "time_s": round(dt, 1), "verified": verified,
            "dest": os.path.relpath(dest, ROOT) if dest else ""}

def main():
    jobs = []
    for ds in DATASETS:
        for path in sorted(__import__("glob").glob(os.path.join(ROOT, "Bench", ds, "Problems", "*.lean"))):
            jobs.append((ds, path))
    print(f"processing {len(jobs)} files with {WORKERS} workers", flush=True)
    rows = []
    t0 = time.time()
    with ThreadPoolExecutor(max_workers=WORKERS) as ex:
        futs = {ex.submit(process, ds, p): (ds, p) for ds, p in jobs}
        for i, f in enumerate(as_completed(futs), 1):
            try: r = f.result()
            except Exception as e:
                ds, p = futs[f]; r = {"dataset": ds, "file": os.path.basename(p)[:-5], "outcome": "RUNNER_ERROR",
                                      "method": str(e)[:60], "cost_cents": 0, "time_s": 0, "verified": "", "dest": ""}
            rows.append(r)
            print(f"[{i}/{len(jobs)}] {r['dataset']}/{r['file']}: {r['outcome']} ({r['method']}) {r['cost_cents']}¢ {r['time_s']}s {r['verified']}", flush=True)
            with open(os.path.join(ROOT, "scripts", "overnight_progress.jsonl"), "a") as fh:
                fh.write(__import__("json").dumps(r) + "\n")
            if i % 20 == 0: write_report(rows, time.time() - t0)  # periodic snapshot
    write_report(rows, time.time() - t0)

def write_report(rows, wall):
    with open(os.path.join(ROOT, "scripts", "overnight_results.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
    from collections import Counter
    def tally(ds):
        rs = [r for r in rows if r["dataset"] == ds]
        c = Counter(r["outcome"].split("(")[0] for r in rs)
        cost = sum(r["cost_cents"] for r in rs)
        return rs, c, cost
    lines = ["# Overnight `sql_equiv_llm` run\n", f"Wall time: {wall/3600:.2f} h · Total files: {len(rows)}\n"]
    tot_cost = 0
    for ds in DATASETS:
        rs, c, cost = tally(ds); tot_cost += cost
        lines.append(f"\n## {ds} ({len(rs)} files) — {cost:.1f}¢\n")
        for k in ["PROVED", "DISPROVED", "INCONCLUSIVE", "TIMEOUT", "ELAB_ERROR", "RUNNER_ERROR"]:
            if c.get(k): lines.append(f"- {k}: {c[k]}")
    lines.append(f"\n**Total estimated cost: {tot_cost:.1f}¢ (${tot_cost/100:.2f})**\n")
    lines.append("\n## Per-file\n\n| dataset | file | outcome | method | cost¢ | time s | verified | artifact |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for r in sorted(rows, key=lambda r: (r["dataset"], r["file"])):
        lines.append(f"| {r['dataset']} | {r['file']} | {r['outcome']} | {r['method']} | {r['cost_cents']} | {r['time_s']} | {r['verified']} | {r['dest']} |")
    open(os.path.join(ROOT, "scripts", "overnight_report.md"), "w").write("\n".join(lines))
    print("REPORT WRITTEN: scripts/overnight_report.md + overnight_results.csv", flush=True)

if __name__ == "__main__":
    main()
